"""Generating the logout path, URL and form of a registered firewall."""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING, cast, final
from urllib.parse import urlencode, urlsplit

from xtr_security_core.exception import InvalidArgumentError

from .logout_form import LogoutForm

if TYPE_CHECKING:
    from collections.abc import Callable

    from xtr_security_core.authentication.token.storage.token_storage_interface import (
        TokenStorageInterface,
    )
    from xtr_security_csrf.csrf_token_manager_interface import CsrfTokenManagerInterface

__all__ = ["LogoutUrlGenerator"]


@dataclass(frozen=True, slots=True)
class _RegisteredLogout:
    """One firewall's logout, as registered."""

    path: str
    csrf_token_id: str | None
    csrf_parameter: str | None
    csrf_token_manager: CsrfTokenManagerInterface | None
    context: str | None


def _is_absolute_url(path: str) -> bool:
    """Tell whether ``path`` already is an absolute URL."""
    split = urlsplit(path)
    return split.scheme != "" and split.netloc != ""


@final
class LogoutUrlGenerator:
    """Provides the logout path, URL and form of a registered firewall.

    Each firewall with a logout registers itself here — its path, the
    cross-site request forgery token its logout asks for, and the context it
    runs in — and whatever renders a page asks for the logout's address by
    the firewall's name, or without one: the firewall the current request
    runs under is found from the token the request is authenticated by, or
    the one the application last named, or the one sharing the current
    context, in that order.

    A path is always a literal path — an absolute path (``/logout``) or an
    absolute URL (``https://…``) — never a route name: this stack has no
    routing component to resolve one by, the recorded deviation. The URI a
    path becomes in :meth:`get_logout_url` is written by the injected URI
    builder — the path itself by default, an absolute URL when the
    application's builder writes one.
    """

    __slots__ = (
        "_current_context",
        "_current_firewall",
        "_listeners",
        "_token_storage",
        "_uri_builder",
    )

    def __init__(
        self,
        uri_builder: Callable[[str], str] | None = None,
        token_storage: TokenStorageInterface | None = None,
    ) -> None:
        """Record the URI builder and the token storage the resolution reads.

        Args:
            uri_builder: Writes the absolute URI a path becomes in
                :meth:`get_logout_url`. Left out, a path is its own URI — a
                ``Location`` may carry one, and the framework resolves it
                against the request's host.
            token_storage: Read to find the firewall the current request is
                authenticated by — the token it holds names the firewall
                that authenticated it. Left out, a keyless lookup resolves
                over the current firewall alone.
        """
        self._listeners: dict[str, _RegisteredLogout] = {}
        self._uri_builder = uri_builder
        self._token_storage = token_storage
        self._current_firewall: str | None = None
        self._current_context: str | None = None

    def register_listener(  # noqa: PLR0913, PLR0917 -- the registered shape: one firewall's logout, every part of it
        self,
        key: str,
        path: str,
        csrf_token_id: str | None,
        csrf_parameter: str | None,
        csrf_token_manager: CsrfTokenManagerInterface | None = None,
        context: str | None = None,
    ) -> None:
        """Record one firewall's logout, for the generator to generate from.

        Args:
            key: The firewall's name — the key its logout is generated by.
            path: The path a request asks that firewall's logout by.
            csrf_token_id: The id the forgery token is stored under, or
                ``None`` while the firewall's logout asks for no proof.
            csrf_parameter: The name a request carries the forgery token
                under, or ``None`` with the id.
            csrf_token_manager: Mints the token the generated address
                carries, or ``None`` while the generated address carries
                none.
            context: The context the firewall runs in, matched when no
                firewall is named — the shared context of a firewall pair,
                a stateless API beside a stateful login.
        """
        self._listeners[key] = _RegisteredLogout(
            path,
            csrf_token_id,
            csrf_parameter,
            csrf_token_manager,
            context,
        )

    async def get_logout_path(self, key: str | None = None) -> str:
        """Generate the logout path of ``key``, or of the current firewall.

        The path itself — the configured logout path, or the absolute URL it
        is when it was configured as one — beside the query a forgery token
        adds, when the registered logout carries one.
        """
        registered = await self._registered(key)
        return self._with_query(registered.path, await self._parameters(registered))

    async def get_logout_url(self, key: str | None = None) -> str:
        """Generate the absolute logout URL of ``key``, or of the current firewall.

        The path through the URI builder — the path itself while no builder
        writes absolute URIs — beside the query a forgery token adds, when
        the registered logout carries one.
        """
        registered = await self._registered(key)
        return self._with_query(self._uri(registered.path), await self._parameters(registered))

    async def get_logout_form(self, key: str | None = None) -> LogoutForm:
        """Return the action and the hidden fields of a form triggering the logout.

        Unlike the URLs, this keeps the forgery token out of the address
        bar, and suits a logout restricted to ``POST`` requests. Render each
        field as a hidden input of a form posted to the action; the
        ``csrf_field`` key names the field that carries the token, for a
        template to mark for client-side scripts, or is ``None`` when the
        form carries none.
        """
        registered = await self._registered(key)
        fields = await self._parameters(registered)
        return LogoutForm(
            action=registered.path,
            fields=fields,
            csrf_field=registered.csrf_parameter if registered.csrf_parameter in fields else None,
        )

    def set_current_firewall(self, key: str | None = None, context: str | None = None) -> None:
        """Name the firewall a keyless generation generates for.

        The application — or the bundle wiring it — names the firewall while
        running a request of its own, so a template generating a logout
        address with no key names this firewall's. The context is matched
        when no firewall is named, against the context each registered
        logout carries.
        """
        self._current_firewall = key
        self._current_context = context

    def reset(self) -> None:
        """Put the current-firewall tracking back to no firewall.

        What a request named does not answer for the next one: a worker or
        a test that reuses the generator starts untracked, and a keyless
        generation resolves over the token or fails loudly instead of
        answering for a firewall no request of its own runs under.

        Implemented without the service contracts' ``ResetInterface``: this
        package does not depend on that one, and this method is the whole of
        what the interface asks.
        """
        self._current_firewall = None
        self._current_context = None

    async def _registered(self, key: str | None) -> _RegisteredLogout:
        """Resolve ``key`` — or the current firewall — to its registered logout.

        The resolution order is the key, when one is given; the firewall the
        current token names; the firewall the application last named; and
        the one sharing the current context. Anything else is the caller's
        mistake to name.

        Raises:
            InvalidArgumentError: When ``key`` names no registered firewall,
                or no key was given and no token, current firewall or context
                resolves one.
        """
        if key is not None:
            return self._by_key(key)
        from_the_token = self._from_the_token()
        if from_the_token is not None:
            return from_the_token
        current = self._current_firewall
        if current is not None and current in self._listeners:
            return self._listeners[current]
        if self._current_context is not None:
            for registered in self._listeners.values():
                if registered.context == self._current_context:
                    return registered
        if current is None:
            raise InvalidArgumentError(
                "This request is not behind a firewall; pass the firewall name "
                "to generate a logout URL.",
            )
        raise InvalidArgumentError(
            "Unable to find a logout listener for the current firewall; pass the "
            "firewall name to generate a logout URL.",
        )

    def _by_key(self, key: str) -> _RegisteredLogout:
        """Return the logout registered under ``key``.

        Raises:
            InvalidArgumentError: When no logout is registered under ``key``.
        """
        try:
            return self._listeners[key]
        except KeyError as error:
            raise InvalidArgumentError(
                f'No logout listener is registered for the firewall "{key}".',
            ) from error

    def _from_the_token(self) -> _RegisteredLogout | None:
        """Return the logout of the firewall the current token names, if any.

        The token the storage holds names the firewall that authenticated it
        — the one a request of this firewall runs under, so its logout is
        the one a keyless generation means. A token of a kind that carries
        no firewall name, or no token at all, resolves nothing.
        """
        if self._token_storage is None:
            return None
        token = self._token_storage.get_token()
        # The cast says what narrowing cannot: a token of the
        # post-authentication kind carries the name of the firewall that
        # authenticated it, and one of another kind resolves nothing.
        firewall_name = cast("Callable[[], str] | None", getattr(token, "get_firewall_name", None))
        if firewall_name is None:
            return None
        return self._listeners.get(firewall_name())

    @staticmethod
    async def _parameters(registered: _RegisteredLogout) -> dict[str, str]:
        """Return the query parameters the registered logout's address carries.

        Only a forgery token: the value the registered manager mints under
        the registered id, carried under the registered parameter name. A
        registration that names no manager, no id or no parameter name
        carries none — its address is the path alone.
        """
        manager = registered.csrf_token_manager
        if manager is None or registered.csrf_token_id is None or registered.csrf_parameter is None:
            return {}
        token = await manager.get_token(registered.csrf_token_id)
        return {registered.csrf_parameter: token.get_value()}

    def _uri(self, path: str) -> str:
        """Return ``path`` as the URI the logout URL carries.

        An absolute URL is returned as it is; an absolute path goes through
        the URI builder — the path itself while none is injected. Anything
        else is a route name, which nothing here can resolve.

        Raises:
            InvalidArgumentError: When ``path`` is neither an absolute path
                nor an absolute URL.
        """
        if _is_absolute_url(path):
            return path
        if not path.startswith("/"):
            raise InvalidArgumentError(
                f"The path {path!r} is not an absolute path; route names are not supported, "
                "only literal paths.",
            )
        return path if self._uri_builder is None else self._uri_builder(path)

    @staticmethod
    def _with_query(url: str, parameters: dict[str, str]) -> str:
        """Return ``url`` beside ``parameters`` as its query string."""
        if not parameters:
            return url
        separator = "&" if "?" in url else "?"
        return f"{url}{separator}{urlencode(parameters)}"
